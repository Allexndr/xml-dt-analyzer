"""File storage for the prototype: originals on disk, metadata and history as JSON.

Originals are stored byte-for-byte and never modified. Ownership is bound to a
hash of the anonymous session token, so the token itself is never persisted.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import threading
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path

RETENTION = timedelta(days=7)
# Files of signed-in users are kept until the user deletes them.
ACCOUNT_RETENTION = timedelta(days=3650)


def now() -> datetime:
    return datetime.now(timezone.utc)


def owner_key(session_token: str) -> str:
    return hashlib.sha256(("xmldt-owner:" + session_token).encode()).hexdigest()


@dataclass
class FileMeta:
    id: str
    owner: str
    name: str
    size: int
    sha256: str
    uploaded_at: str
    expires_at: str
    encoding: str = ""
    status: str = "ready"
    error: dict | None = None
    schema: dict | None = None
    xsd_valid: bool | None = None
    xsd_error_count: int = 0
    goods_items: int | None = None
    xsd_errors: list[dict] = field(default_factory=list)

    def public(self) -> dict:
        d = asdict(self)
        d.pop("owner")
        d.pop("xsd_errors")
        return d


class Store:
    def __init__(self, root: Path):
        self.root = root
        self.root.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()

    def _dir(self, file_id: str) -> Path:
        # ids are uuid4 hex generated by us; validate anyway before touching the filesystem
        if len(file_id) != 32 or any(c not in "0123456789abcdef" for c in file_id):
            raise KeyError(file_id)
        return self.root / file_id

    def create(self, owner: str, name: str, data: bytes) -> FileMeta:
        fid = uuid.uuid4().hex
        d = self._dir(fid)
        d.mkdir()
        (d / "original.xml").write_bytes(data)
        t = now()
        meta = FileMeta(id=fid, owner=owner, name=name[:255], size=len(data),
                        sha256=hashlib.sha256(data).hexdigest(),
                        uploaded_at=t.isoformat(), expires_at=(t + RETENTION).isoformat())
        self.save(meta)
        return meta

    def save(self, meta: FileMeta, *, ownership: bool = False) -> None:
        """Atomically write metadata. Ownership (owner, expiry) changes only with ``ownership=True``,
        so a slow analysis cannot revert a migration to an account that happened meanwhile."""
        d = self._dir(meta.id)
        with self._lock:
            cur = d / "meta.json"
            if not ownership and cur.exists():
                try:
                    disk = json.loads(cur.read_text(encoding="utf-8"))
                    meta.owner, meta.expires_at = disk["owner"], disk["expires_at"]
                except (OSError, ValueError, KeyError):
                    pass
            tmp = d / f"meta.json.{uuid.uuid4().hex}.tmp"
            tmp.write_text(json.dumps(asdict(meta), ensure_ascii=False), encoding="utf-8")
            os.replace(tmp, cur)

    def get(self, owner: str, file_id: str) -> FileMeta:
        try:
            p = self._dir(file_id) / "meta.json"
        except KeyError:
            raise KeyError(file_id) from None
        if not p.exists():
            raise KeyError(file_id)
        meta = FileMeta(**json.loads(p.read_text(encoding="utf-8")))
        if meta.owner != owner or datetime.fromisoformat(meta.expires_at) < now():
            raise KeyError(file_id)  # do not reveal other owners' files
        return meta

    def list(self, owner: str) -> list[FileMeta]:
        out = []
        for d in self.root.iterdir():
            try:
                out.append(self.get(owner, d.name))
            except (KeyError, ValueError, json.JSONDecodeError):
                continue
        return sorted(out, key=lambda m: m.uploaded_at, reverse=True)

    def migrate_anonymous(self, anon_owner: str, user_owner: str) -> int:
        return migrate_anonymous(self, anon_owner, user_owner)

    def original(self, meta: FileMeta) -> bytes:
        return (self._dir(meta.id) / "original.xml").read_bytes()

    def delete(self, meta: FileMeta) -> None:
        shutil.rmtree(self._dir(meta.id), ignore_errors=True)

    def purge_expired(self) -> int:
        n = 0
        for d in list(self.root.iterdir()):
            p = d / "meta.json"
            try:
                exp = datetime.fromisoformat(json.loads(p.read_text(encoding="utf-8"))["expires_at"])
            except (OSError, ValueError, KeyError, json.JSONDecodeError):
                continue
            if exp < now():
                shutil.rmtree(d, ignore_errors=True)
                n += 1
        return n

    # ---- history ------------------------------------------------------
    def add_history(self, meta: FileMeta, kind: str, title: str, request: dict, result: dict) -> dict:
        entry = {"id": uuid.uuid4().hex, "at": now().isoformat(), "kind": kind, "title": title,
                 "request": request, "result": result}
        with self._lock:
            with open(self._dir(meta.id) / "history.jsonl", "a", encoding="utf-8") as f:
                f.write(json.dumps(entry, ensure_ascii=False) + "\n")
        return entry

    def history(self, meta: FileMeta, limit: int = 100) -> list[dict]:
        p = self._dir(meta.id) / "history.jsonl"
        if not p.exists():
            return []
        lines = p.read_text(encoding="utf-8").splitlines()[-limit:]
        return [json.loads(x) for x in reversed(lines)]


def migrate_anonymous(store: Store, anon_owner: str, user_owner: str) -> int:
    """Reassign all non-expired files of an anonymous owner to a signed-in user.

    Moved files get a far-future expiry (users keep files until they delete them).
    Returns the number of files moved.
    """
    if anon_owner == user_owner:
        return 0
    if not isinstance(store, Store):  # database-backed store has its own implementation
        return store.migrate_anonymous(anon_owner, user_owner)
    moved = 0
    far = (now() + ACCOUNT_RETENTION).isoformat()
    for d in list(store.root.iterdir()):
        try:
            meta = FileMeta(**json.loads((d / "meta.json").read_text(encoding="utf-8")))
            if meta.owner != anon_owner or datetime.fromisoformat(meta.expires_at) < now():
                continue
            meta.owner = user_owner
            meta.expires_at = far
            store.save(meta, ownership=True)
            moved += 1
        except (OSError, ValueError, TypeError, KeyError, json.JSONDecodeError):
            continue
    return moved


_DB_SCHEMA = """
CREATE TABLE IF NOT EXISTS files (
  id TEXT PRIMARY KEY, owner TEXT NOT NULL, expires_at TEXT NOT NULL, uploaded_at TEXT NOT NULL,
  meta TEXT NOT NULL, data BLOB NOT NULL);
CREATE INDEX IF NOT EXISTS files_owner ON files(owner);
CREATE TABLE IF NOT EXISTS history (
  id INTEGER PRIMARY KEY AUTOINCREMENT, file_id TEXT NOT NULL, at REAL NOT NULL, entry TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS history_file ON history(file_id, id);
CREATE TABLE IF NOT EXISTS kv (ns TEXT NOT NULL, k TEXT NOT NULL, v TEXT NOT NULL, PRIMARY KEY (ns, k));
"""


class DbStore:
    """Same interface as ``Store`` but keeps originals, metadata and history in a database
    (Postgres on serverless hosting, where the filesystem is not persistent)."""

    def __init__(self, sqlite_path: Path):
        self.sqlite_path = sqlite_path

    def _c(self):
        from xmldt.api import db

        return db.connect(self.sqlite_path, _DB_SCHEMA)

    @staticmethod
    def _check_id(file_id: str) -> None:
        if len(file_id) != 32 or any(ch not in "0123456789abcdef" for ch in file_id):
            raise KeyError(file_id)

    def create(self, owner: str, name: str, data: bytes) -> FileMeta:
        fid = uuid.uuid4().hex
        t = now()
        meta = FileMeta(id=fid, owner=owner, name=name[:255], size=len(data),
                        sha256=hashlib.sha256(data).hexdigest(),
                        uploaded_at=t.isoformat(), expires_at=(t + RETENTION).isoformat())
        c = self._c()
        try:
            c.execute("INSERT INTO files(id, owner, expires_at, uploaded_at, meta, data) VALUES (?,?,?,?,?,?)",
                      (fid, owner, meta.expires_at, meta.uploaded_at, json.dumps(asdict(meta), ensure_ascii=False), data))
        finally:
            c.close()
        return meta

    def save(self, meta: FileMeta, *, ownership: bool = False) -> None:
        c = self._c()
        try:
            if ownership:
                c.execute("UPDATE files SET owner=?, expires_at=?, meta=? WHERE id=?",
                          (meta.owner, meta.expires_at, json.dumps(asdict(meta), ensure_ascii=False), meta.id))
            else:  # never change ownership from an analysis write (see Store.save)
                row = c.execute("SELECT owner, expires_at FROM files WHERE id=?", (meta.id,)).fetchone()
                if row is None:
                    return
                meta.owner, meta.expires_at = row["owner"], row["expires_at"]
                c.execute("UPDATE files SET meta=? WHERE id=?", (json.dumps(asdict(meta), ensure_ascii=False), meta.id))
        finally:
            c.close()

    def get(self, owner: str, file_id: str) -> FileMeta:
        self._check_id(file_id)
        c = self._c()
        try:
            row = c.execute("SELECT meta FROM files WHERE id=? AND owner=? AND expires_at>?",
                            (file_id, owner, now().isoformat())).fetchone()
        finally:
            c.close()
        if row is None:
            raise KeyError(file_id)
        return FileMeta(**json.loads(row["meta"]))

    def list(self, owner: str) -> list[FileMeta]:
        c = self._c()
        try:
            rows = c.execute("SELECT meta FROM files WHERE owner=? AND expires_at>? ORDER BY uploaded_at DESC",
                             (owner, now().isoformat())).fetchall()
        finally:
            c.close()
        return [FileMeta(**json.loads(r["meta"])) for r in rows]

    def original(self, meta: FileMeta) -> bytes:
        c = self._c()
        try:
            row = c.execute("SELECT data FROM files WHERE id=?", (meta.id,)).fetchone()
        finally:
            c.close()
        return bytes(row["data"]) if row else b""

    def delete(self, meta: FileMeta) -> None:
        c = self._c()
        try:
            c.execute("DELETE FROM history WHERE file_id=?", (meta.id,))
            c.execute("DELETE FROM files WHERE id=?", (meta.id,))
        finally:
            c.close()

    def purge_expired(self) -> int:
        c = self._c()
        try:
            t = now().isoformat()
            c.execute("DELETE FROM history WHERE file_id IN (SELECT id FROM files WHERE expires_at<?)", (t,))
            c.execute("DELETE FROM files WHERE expires_at<?", (t,))
        finally:
            c.close()
        return 0

    def migrate_anonymous(self, anon_owner: str, user_owner: str) -> int:
        if anon_owner == user_owner:
            return 0
        far = (now() + ACCOUNT_RETENTION).isoformat()
        moved = 0
        for meta in self.list(anon_owner):
            meta.owner, meta.expires_at = user_owner, far
            self.save(meta, ownership=True)
            moved += 1
        return moved

    def add_history(self, meta: FileMeta, kind: str, title: str, request: dict, result: dict) -> dict:
        entry = {"id": uuid.uuid4().hex, "at": now().isoformat(), "kind": kind, "title": title,
                 "request": request, "result": result}
        c = self._c()
        try:
            c.execute("INSERT INTO history(file_id, at, entry) VALUES (?,?,?)",
                      (meta.id, now().timestamp(), json.dumps(entry, ensure_ascii=False)))
        finally:
            c.close()
        return entry

    def history(self, meta: FileMeta, limit: int = 100) -> list[dict]:
        c = self._c()
        try:
            rows = c.execute("SELECT entry FROM history WHERE file_id=? ORDER BY id DESC LIMIT ?",
                             (meta.id, limit)).fetchall()
        finally:
            c.close()
        return [json.loads(r["entry"]) for r in rows]

    # small persistent key-value storage for per-owner state (AI settings without keys, dialog state)
    def kv_get(self, ns: str, k: str) -> dict | None:
        c = self._c()
        try:
            row = c.execute("SELECT v FROM kv WHERE ns=? AND k=?", (ns, k)).fetchone()
        finally:
            c.close()
        return json.loads(row["v"]) if row else None

    def kv_put(self, ns: str, k: str, v: dict) -> None:
        c = self._c()
        try:
            c.execute("INSERT INTO kv(ns, k, v) VALUES (?,?,?) ON CONFLICT(ns, k) DO UPDATE SET v=excluded.v",
                      (ns, k, json.dumps(v, ensure_ascii=False)))
        finally:
            c.close()
